/** Converts ISO dates (YYYY-MM-DD) in free text to DD/MM/YYYY and YYYY-MM months to MM/YYYY. */
export function indianDates(text: string): string {
  return text
    .replace(/\b(\d{4})-(\d{2})-(\d{2})\b/g, "$3/$2/$1")
    .replace(/\b(20\d{2})-(0[1-9]|1[0-2])\b(?!-)/g, "$2/$1");
}
